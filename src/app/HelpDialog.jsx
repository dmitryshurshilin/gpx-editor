import { useEffect, useRef } from "react";
export function HelpDialog({ open, onClose }) {
  const dialog = useRef(null);
  useEffect(() => {
    if (!open) return;
    const previous = document.activeElement;
    dialog.current.showModal();
    return () => {
      dialog.current?.close();
      previous?.focus({ preventScroll: true });
    };
  }, [open]);
  return (
    <dialog
      id="help-dialog"
      ref={dialog}
      onClose={onClose}
      onClick={(event) => {
        if (event.target !== event.currentTarget) return;
        const r = event.currentTarget.getBoundingClientRect();
        if (
          event.clientX < r.left ||
          event.clientX > r.right ||
          event.clientY < r.top ||
          event.clientY > r.bottom
        )
          event.currentTarget.close();
      }}
      aria-labelledby="help-title"
    >
      <div className="dialog-heading">
        <h2 id="help-title">Как пользоваться GPX Editor</h2>
        <button
          id="help-close"
          onClick={() => dialog.current.close()}
          aria-label="Закрыть инструкцию"
        >
          ×
        </button>
      </div>
      <ol className="help-steps">
        <li>
          <strong>Загрузите GPX.</strong> Выберите файл или перетащите его в
          область загрузки. Для знакомства нажмите «Попробовать на примере».
          Трек обрабатывается в браузере и не отправляется на сервер.
        </li>
        <li>
          <strong>Добавьте и переместите точки.</strong> В режиме
          «Редактирование» нажмите на линию между точками, чтобы добавить новую.
          Перетащите точку мышью, чтобы изменить её координаты. Исходный участок
          во время перемещения показывается полупрозрачным пунктиром, новое
          положение — сплошной линией.
        </li>
        <li>
          <strong>Удалите одну точку.</strong> Дважды нажмите на неё в режиме
          «Редактирование». Соседние точки соединятся прямым отрезком внутри
          того же сегмента.
        </li>
        <li>
          <strong>Удалите фрагмент.</strong> Включите «Выделение», обведите
          точки рамкой и нажмите «Удалить точки». «Сбросить» снимает выделение.
        </li>
        <li>
          <strong>Попробуйте автокоррекцию.</strong> Кнопка «Автокоррекция · 500
          м» строит предпросмотр: оранжевым отмечаются вылеты между скачками
          более 500 м с подтверждённым возвратом, зелёным пунктиром — будущие
          соединения. Проверьте карту и нажмите «Удалить найденные точки» или
          «Отменить». До подтверждения GPX не меняется. Незавершённые вылеты
          сохраняются. Редактирование трека сбрасывает предпросмотр; Esc
          отменяет его.
        </li>
        <li>
          <strong>Разверните карту.</strong> Кнопки «Схема» и «Спутник» в правом
          верхнем углу карты переключают фон, сохраняя трек, масштаб и
          выделение. В режиме редактирования загруженного трека нажмите «На весь
          экран». Можно добавлять и перемещать точки, удаление отключено. Для
          выхода нажмите «Вернуться в нормальный режим (Esc)» или клавишу Esc.
        </li>
        <li>
          <strong>Сохраните результат.</strong> Для снимка карты нажмите
          «Скриншот области», обведите область мышью — PNG сохранится на
          устройство. Кнопки интерфейса в снимок не попадают; подпись источника
          карты сохраняется. Esc отменяет выделение для снимка. «Отменить
          изменение» отменяет последнее добавление, перемещение, удаление или
          автокоррекцию. Исправленный код виден под картой. Нажмите «Скачать
          GPX», чтобы сохранить файл.
        </li>
      </ol>
      <p className="help-note">
        Для загрузки карты нужен интернет. Закрыть инструкцию можно кнопкой ×,
        клавишей Esc или нажатием вне окна.
      </p>
    </dialog>
  );
}
